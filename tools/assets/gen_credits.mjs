// Builds public/credits.md and src/game/creditsData.js from tools/assets/manifest.json.
//   node tools/assets/gen_credits.mjs
import fs from 'node:fs';
const root = new URL('../../', import.meta.url);
const { assets } = JSON.parse(fs.readFileSync(new URL('tools/assets/manifest.json', root), 'utf8'));
const LICENSE_URL = { 'CC-BY-4.0': 'http://creativecommons.org/licenses/by/4.0/', 'CC0-1.0': 'https://creativecommons.org/publicdomain/zero/1.0/' };
const rows = assets.map((a) => ({ title: a.title, author: a.author, url: a.url, license: a.license, category: a.category }));
let md = '# Reel World - 3D model credits\n\nThese models were downloaded from Sketchfab, cleaned and compressed for the game (decimated, textures resized, re-posed) with tools/blender/import_assets.py.\n\n';
for (const r of rows) md += `- "${r.title}" by ${r.author} (${r.url}), licensed under [${r.license}](${LICENSE_URL[r.license] || ''}). Modified for use in this game.\n`;
fs.writeFileSync(new URL('public/credits.md', root), md);
fs.writeFileSync(new URL('src/game/creditsData.js', root), `// generated by tools/assets/gen_credits.mjs from tools/assets/manifest.json - do not edit\nexport const MODEL_CREDITS = ${JSON.stringify(rows, null, 2)};\n`);
console.log('credits for', rows.length, 'models');
